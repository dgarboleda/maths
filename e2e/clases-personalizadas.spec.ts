import { expect, test, type Locator } from "@playwright/test";
import { crearHijo, entrarAlEspacio, entrarComoFamilia, registrarPadre } from "./utilidades";

/** Escribe las respuestas de una pregunta (una fila por respuesta) y marca la correcta. */
async function answers(question: Locator, options: string[], correct: string) {
  for (let i = 2; i < options.length; i++) await question.getByRole("button", { name: "Añadir respuesta" }).click();
  for (const [i, option] of options.entries()) await question.getByLabel(`Respuesta ${i + 1}`, { exact: true }).fill(option);
  await question.getByLabel(`La respuesta ${options.indexOf(correct) + 1} es la correcta`).check();
}

test("una familia publica una clase y el alumno resuelve sus preguntas", async ({ page }) => {
  const correo = await registrarPadre(page);
  const child = await crearHijo(page, { nombre: "Alex" });
  const childId = await entrarAlEspacio(page, child.nombre, child.pin);
  await entrarComoFamilia(page, correo);
  await page.goto("/panel/clases");
  await page.getByLabel("Tema", { exact: true }).fill("Aritmética");
  await page.getByLabel("Título de la clase").fill("Sumar dos números");
  await page.getByLabel("Contenido de la clase").fill("Sumar es reunir cantidades.");
  await page.getByRole("button", { name: "Añadir recurso interactivo" }).click();
  await page.getByLabel("Título del recurso").fill("Explora la recta");
  await page.getByLabel("Mínimo").fill("-4");
  await page.getByLabel("Máximo").fill("8");
  await page.getByLabel("Valor inicial").fill("2");
  await page.getByText("Probar este recurso").click();
  await expect(page.getByRole("img", { name: /de -4 a 8, valor seleccionado 2/ })).toBeVisible();
  await page.getByRole("button", { name: "Añadir recurso interactivo" }).click();
  await page.getByRole("combobox", { name: "Modelo", exact: true }).nth(1).selectOption("probability");
  await page.getByText("Probar este recurso").nth(1).click();
  await expect(page.getByLabel(/Fichas rojas/)).toBeVisible();
  await page.getByRole("button", { name: "Añadir pregunta", exact: true }).click();
  await page.getByLabel("Enunciado").fill("¿Cuánto es 2 + 2?");
  const first = page.getByRole("group", { name: "Pregunta 1" });
  await answers(first, ["3", "4"], "4");
  await first.getByLabel("Explicación").fill("Dos más dos son cuatro.");
  await first.getByLabel("Pista").fill("Cuenta con los dedos.");
  await first.getByLabel("Comentario si elige la respuesta 1").fill("Te has quedado a uno.");
  await page.getByRole("button", { name: "Añadir pregunta", exact: true }).click();
  const second = page.getByRole("group", { name: "Pregunta 2" });
  await second.getByLabel("Enunciado").fill("¿Cuánto es 1 + 1?");
  await answers(second, ["2", "3"], "2");
  await page.getByRole("button", { name: "Publicar para alumnos" }).click();
  await expect(page.getByText("Clase publicada para tus alumnos.")).toBeVisible();
  await page.goto(`/jugar/${childId}/aprende`);
  const mine = page.getByRole("region", { name: "Clases creadas para ti" });
  await expect(mine.getByRole("heading", { name: "Aritmética", exact: true })).toBeVisible();
  await mine.getByRole("link", { name: "Sumar dos números" }).click();
  await expect(page.getByText("Sumar es reunir cantidades.")).toBeVisible();
  await expect(page.getByRole("heading", { name: "Explora la recta" })).toBeVisible();
  const slider = page.getByRole("slider", { name: /Valor/ });
  await expect(slider).toHaveValue("2");
  await slider.focus();
  await slider.press("ArrowRight");
  await expect(page.getByRole("img", { name: /valor seleccionado 3/ })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Probabilidad", exact: true })).toBeVisible();
  await expect(page.getByLabel(/Fichas rojas/)).toBeVisible();
  await page.getByRole("button", { name: "Empezar preguntas" }).click();
  await page.getByRole("button", { name: "3", exact: true }).click();
  await expect(page.getByText("Inténtalo de nuevo. Te has quedado a uno.")).toBeVisible();
  await expect(page.getByText("Pista: Cuenta con los dedos.")).toBeVisible();
  await page.getByRole("button", { name: "4", exact: true }).click();
  await expect(page.getByText(/¡Correcto!/)).toBeVisible();
  await page.getByRole("button", { name: "Siguiente pregunta" }).click();
  await expect(page.getByText("¿Cuánto es 1 + 1?")).toBeVisible();
  await page.getByRole("button", { name: "2", exact: true }).click();
  await expect(page.getByRole("button", { name: "Terminar clase" })).toBeVisible();
  await page.getByRole("button", { name: "Terminar clase" }).click();
  await expect(page.getByText("¡Terminaste la clase!")).toBeVisible();
  await expect(page.getByRole("link", { name: "Elegir otra clase" })).toHaveAttribute("href", `/jugar/${childId}/aprende`);
  await page.reload();
  await page.getByRole("button", { name: "Empezar preguntas" }).click();
  await expect(page.getByText("¡Terminaste la clase!")).toBeVisible();
  await expect(page.getByRole("link", { name: "Elegir otra clase" })).toHaveAttribute("href", `/jugar/${childId}/aprende`);
});

test("una clase personalizada muestra respuestas de texto en el minijuego", async ({ page }) => {
  const correo = await registrarPadre(page);
  const child = await crearHijo(page, { nombre: "Sol" });
  const childId = await entrarAlEspacio(page, child.nombre, child.pin);
  await entrarComoFamilia(page, correo);
  await page.goto("/panel/clases");
  await page.getByLabel("Tema", { exact: true }).fill("Formas");
  await page.getByLabel("Título de la clase").fill("Formas planas");
  await page.getByLabel("Contenido de la clase").fill("Las figuras se distinguen por sus lados.");
  await page.getByLabel("Minijuego").selectOption("breakout");
  await page.getByRole("button", { name: "Añadir pregunta", exact: true }).click();
  await page.getByLabel("Enunciado").fill("¿Qué figura tiene tres lados?");
  await answers(page.getByRole("group", { name: "Pregunta 1" }), ["Círculo", "Cuadrado", "Triángulo", "Óvalo", "Rectángulo"], "Triángulo");
  await page.getByRole("button", { name: "Publicar para alumnos" }).click();
  await expect(page.getByText("Clase publicada para tus alumnos.")).toBeVisible();
  await page.goto(`/jugar/${childId}/aprende`);
  await page.getByRole("region", { name: "Clases creadas para ti" }).getByRole("link", { name: "Formas planas" }).click();
  await page.getByRole("button", { name: "Empezar preguntas" }).click();
  await page.getByRole("button", { name: "¡Empezar!" }).click();
  await page.getByRole("button", { name: "Apuntar al bloque Triángulo" }).click();
  const board = page.locator("[data-breakout-board]");
  const barriers = await board.locator("[data-barrier]").count();
  await page.getByRole("button", { name: "Lanzar la pelota" }).click();
  if (barriers) {
    await expect(board.locator("[data-barrier]")).toHaveCount(barriers - 1);
    await expect(board).toHaveAttribute("data-held", "true");
    await page.getByRole("button", { name: "Lanzar la pelota" }).click();
  }
  await expect(page.getByText(/¡Correcto!/)).toBeVisible();
  await page.getByRole("button", { name: "Terminar clase" }).click();
  await expect(page.getByText("¡Terminaste la clase!")).toBeVisible();
  await expect(page.getByRole("link", { name: "Elegir otra clase" })).toHaveAttribute("href", `/jugar/${childId}/aprende`);
});

